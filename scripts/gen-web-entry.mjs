// Generate the Vite ESM entry for the legacy app (Backlog 1.4).
//
// `vite build` cannot bundle classic <script src> tags. So we derive, from the
// legacy index.html (the single source of script order):
//   - packages/web/src/main.ts  — side-effect imports of every local script, in
//     order, so they enter the module graph and get bundled.
//   - index.vite.html (repo root) — the legacy HTML with the local <script> block
//     replaced by one module entry. Kept at repo root so every relative asset
//     path (styles.css, data/, sw.js, manifest) resolves exactly as in legacy.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { MIGRATED } from "./migrated.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
// index.src.html is the hand-authored source template (the classic <script>
// order + HTML shell). After the Vite cutover the shipped index.html IS the
// built bundle, so the source of truth for script order lives here.
const html = readFileSync(join(ROOT, "index.src.html"), "utf8");

// Local scripts in document order (skip CDN https URLs).
const re = /<script\s+src="(?!https?:)([^"]+\.js)"><\/script>/g;
const scripts = [];
let m;
while ((m = re.exec(html))) scripts.push(m[1]);
if (!scripts.length) {
  console.error("[gen-web-entry] no local scripts found in index.html");
  process.exit(1);
}

// Migrated features: legacy dist script → the TS module that replaces it in the
// Vite build (the legacy index.html still loads the dist version for the no-Vite
// path; the strangler swaps one feature at a time here).
// Migrated features come from the shared manifest (scripts/migrated.mjs): the
// legacy artifact (staged under legacy/deleted/) → the TS module that replaces
// it in the Vite build. The legacy index.html still loads them from
// legacy/deleted/; the build swaps them here.

// main.ts — side-effect imports (relative from packages/web/src to repo root).
const banner =
  "// GENERATED by scripts/gen-web-entry.mjs from index.html — do not edit.\n" +
  "// Side-effect imports of the legacy global scripts, in document order, so\n" +
  "// Vite bundles them. They self-assign to window exactly as before.\n";
// main.ts lives at packages/web/src/ → three levels below the repo root.
const imports = scripts.map((s) => (MIGRATED[s] ? `import "${MIGRATED[s]}";` : `import "../../../${s}";`)).join("\n");
mkdirSync(join(ROOT, "packages", "web", "src"), { recursive: true });
writeFileSync(join(ROOT, "packages", "web", "src", "main.ts"), banner + imports + "\n");

// index.vite.html — legacy HTML minus local scripts, plus the module entry.
let viteHtml = html.replace(re, "");
// collapse the now-empty script region's blank lines a little
viteHtml = viteHtml.replace(/\n{3,}/g, "\n\n");
const entryTag = '<script type="module" src="/packages/web/src/main.ts"></script>';
if (viteHtml.includes("</body>")) {
  viteHtml = viteHtml.replace("</body>", `${entryTag}\n</body>`);
} else {
  viteHtml += `\n${entryTag}\n`;
}
writeFileSync(join(ROOT, "index.vite.html"), viteHtml);

console.log(`[gen-web-entry] ${scripts.length} scripts → packages/web/src/main.ts + index.vite.html`);
